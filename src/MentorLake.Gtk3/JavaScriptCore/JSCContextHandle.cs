/// <summary>
/// <para>
/// Push an exception handler in @context. Whenever a JavaScript exception happens in
/// the #JSCContext, the given @handler will be called. The default #JSCExceptionHandler
/// simply calls jsc_context_throw_exception() to throw the exception to the #JSCContext.
/// If you don&apos;t want to catch the exception, but only get notified about it, call
/// jsc_context_throw_exception() in @handler like the default one does.
/// The last exception handler pushed is the only one used by the #JSCContext, use
/// jsc_context_pop_exception_handler() to remove it and set the previous one. When @handler
/// is removed from the context, @destroy_notify is called with @user_data as parameter.
/// </para>
/// </summary>

/// <param name="context">
/// a #JSCContext
/// </param>
/// <param name="handler">
/// a #JSCExceptionHandler
/// </param>
/// <param name="user_data">
/// user data to pass to @handler
/// </param>
/// <param name="destroy_notify">
/// destroy notifier for @user_data
/// </param>

	public static T PushExceptionHandler<T>(this T context, MentorLake.JavaScriptCore.JSCExceptionHandler handler, IntPtr user_data, MentorLake.GLib.GDestroyNotify destroy_notify) where T : JSCContextHandle
	{
		if (context.IsInvalid) throw new Exception("Invalid handle (JSCContextHandle)");
		JSCContextHandleExterns.jsc_context_push_exception_handler(context, handler, user_data, destroy_notify);
		return context;
	}

